/**
 * Returns a curated molecule if formula or name matches
 */
export function getCuratedMolecule(query: string): CuratedMolecule | null {
  const clean = query.trim().toUpperCase().replace(/\s+/g, '');

  if (CURATED_MOLECULES[clean]) {
    return CURATED_MOLECULES[clean];
  }

  // Check aliases
  for (const mol of Object.values(CURATED_MOLECULES)) {
    if (
      mol.formula.toUpperCase() === clean ||
      mol.name.toUpperCase().replace(/\s+/g, '') === clean ||
      mol.properties.iupacName?.toUpperCase().replace(/\s+/g, '') === clean
    ) {
      return mol;
    }
  }

  return null;
}
